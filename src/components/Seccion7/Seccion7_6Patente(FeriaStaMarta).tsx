const crearPermisosFeriaSantaMarta = (
  filas: [string, string, string, string, string?, string?, string?, string?, string?][]
): PatenteHistorico[] =>
  filas.map(([
    numero,
    fecha,
    fechaPublicacion,
    descripcion,
    ultimaActualizacion = 'Sin Modificaciones',
    tieneEfectosGenerales = 'Sí',
    tipoNorma = 'Decretos Exentos',
    nombreTitulo = 'Permiso Feria Persa Santa Marta',
    enlaceModificacion = 'Sin Modificaciones'
  ]) => ({
    tipoNorma,
    denominacion: 'Patentes y Permisos',
    nombreTitulo,
    numero,
    fecha,
    fechaPublicacion,
    tieneEfectosGenerales,
    ultimaActualizacion,
    descripcion,
    enlacePublicacion: 'PDF',
    enlaceModificacion,
    urlPublicacion: '',
    urlModificacion: ''
  }));

